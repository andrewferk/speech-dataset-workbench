"""The privacy allowlist (ADR-0002/ADR-0009, extended by ADR-0026).

The rule is "captured audio never enters git; generated audio may." Every tracked ``*.wav``
must therefore live in one of the two trees whose WAVs are generated by ``tests/synth.py`` —
the test fixtures and the example ``--data-in`` — so a real captured recording can never be
committed unnoticed. This is the one failure a revert cannot undo, so it lands here rather than
at the end of the project.

Scope is deliberately WAV-only for audio: a stray ``.mp3`` is an ingest abort (ADR-0005), not a
privacy breach, so it is not this test's concern.

**`hypotheses.jsonl` joins the allowlist** (ADR-0026, amending ADR-0021). It is the first artifact
`sdw` produces carrying a transcript of *what a speaker actually said* rather than the Prompt the
operator authored — on the atypical-speech population this product exists for, a Hypothesis of a
departure from the Prompt is unprompted personal utterance. An allowlist, not a prohibition: the
committed Records are entries in it, not holes in it. `run.json` is deliberately not covered.
"""

import subprocess
from pathlib import Path

REPO_ROOT = Path(__file__).parents[2]

# The only trees whose WAVs are synthetic (born under the generator, ADR-0008/ADR-0009).
ALLOWED_PREFIXES = ("tests/fixtures/", "examples/data-in/")

# The Record is text, so the allowlist is one level wider than the audio one: `examples/` ships a
# committed Run beside its `data-in` (ADR-0026).
ALLOWED_RECORD_PREFIXES = ("tests/fixtures/", "examples/")

RECORD_NAME = "hypotheses.jsonl"


def _tracked(*patterns: str) -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", "-z", *patterns],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return [name for name in result.stdout.split("\0") if name]


def test_every_tracked_wav_is_synthetic() -> None:
    offenders = [
        name for name in _tracked("*.wav", "*.WAV") if not name.startswith(ALLOWED_PREFIXES)
    ]
    assert not offenders, (
        "tracked WAV(s) outside the synthetic-audio trees "
        f"{ALLOWED_PREFIXES}: {offenders}. Captured audio must never enter git (ADR-0002)."
    )


def test_every_tracked_hypothesis_record_is_a_demonstration() -> None:
    offenders = [
        name for name in _tracked(RECORD_NAME) if not name.startswith(ALLOWED_RECORD_PREFIXES)
    ]
    assert not offenders, (
        f"tracked {RECORD_NAME} outside the demonstration trees "
        f"{ALLOWED_RECORD_PREFIXES}: {offenders}. A Hypothesis is a transcript of what a speaker "
        "actually said (ADR-0021/ADR-0026)."
    )
