"""The privacy allowlist (ADR-0002/ADR-0009, extended by ADR-0026).

Two artifact classes can carry what a speaker actually said, and each is allowlisted to the trees
where its content is synthetic:

- **Captured audio never enters git; generated audio may.** Every tracked ``*.wav`` must live in one
  of the two trees whose WAVs are generated by ``tests/synth.py`` — the test fixtures and the
  example ``--data-in``.
- **`hypotheses.jsonl` is the first artifact `sdw` produces carrying what a speaker actually said**
  (ADR-0021's finding). Every v0.1 artifact carries *intended* text — the Prompt the operator
  authored — where a Hypothesis is the model's reading of the audio, and on the atypical-speech
  population this product exists for a speaker who departs from the Prompt yields unprompted
  personal speech. Tracked Records are allowlisted to ``examples/`` and
  ``tests/fixtures/``, whose Records are hand-authored or produced over synthetic tones.

Committing either is the one failure a revert cannot undo, which is why both checks land early
rather than at the end of the project.

This is an **allowlist, not a prohibition**, which is what ADR-0026 overturned ADR-0021's rejection
on: a committed golden is an entry rather than a hole. It catches the realistic accident — a Run
directory from the operator's own corpus committed because it is a few kilobytes and looks like test
data. It cannot catch a redirected Report, which has an arbitrary filename and is an accepted
exception (ADR-0026).

Scope stays narrow in both cases: a stray ``.mp3`` is an ingest abort (ADR-0005), not a privacy
breach, and ``run.json`` is deliberately **not** covered — it holds no speaker-derived text, and
policing a file with nothing to protect dilutes a rule whose force comes from covering exactly the
artifacts that can leak.
"""

import subprocess
from pathlib import Path

REPO_ROOT = Path(__file__).parents[2]

# The only trees whose WAVs are synthetic (born under the generator, ADR-0008/ADR-0009).
ALLOWED_WAV_PREFIXES = ("tests/fixtures/", "examples/data-in/")

# The two legitimate entries for a committed Record: the hand-authored Scoring fixtures (ADR-0025)
# and the example's own Run (ADR-0026). Wider than the WAV list by design — the example's Run sits
# beside `data-in/`, not inside it.
ALLOWED_RECORD_PREFIXES = ("tests/fixtures/", "examples/")

RECORD_FILENAME = "hypotheses.jsonl"


def _tracked(*patterns: str) -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", "-z", *patterns],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return [name for name in result.stdout.split("\0") if name]


def test_every_tracked_wav_is_synthetic() -> None:
    offenders = [
        name for name in _tracked("*.wav", "*.WAV") if not name.startswith(ALLOWED_WAV_PREFIXES)
    ]
    assert not offenders, (
        "tracked WAV(s) outside the synthetic-audio trees "
        f"{ALLOWED_WAV_PREFIXES}: {offenders}. Captured audio must never enter git (ADR-0002)."
    )


def test_every_tracked_hypothesis_record_is_synthetic() -> None:
    # The leading `*` is load-bearing: a bare `hypotheses.jsonl` pathspec matches only a Record at
    # the repo root, and the accident this exists to catch is a whole Run directory copied in.
    offenders = [
        name
        for name in _tracked(f"*{RECORD_FILENAME}")
        if not name.startswith(ALLOWED_RECORD_PREFIXES)
    ]
    assert not offenders, (
        f"tracked {RECORD_FILENAME} outside {ALLOWED_RECORD_PREFIXES}: {offenders}. A Record "
        "carries what a speaker actually said, so only synthetic ones may be committed (ADR-0026)."
    )
